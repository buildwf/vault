/**
 * Builds the web UI in `web/` and embeds it in the Worker as `src/ui/assets.ts`,
 * so the Worker serves `/ui` with its own security headers and no asset binding.
 *
 * The prerendered SPA shell carries a few inline bootstrap scripts; their hashes
 * go into the CSP, so no other inline script can run.
 *
 * Run after changing anything in `web/`: `bun run build:ui`.
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join } from "node:path";

const root = join(import.meta.dir, "..");
const web = join(root, "web");

for (const args of [["install", "--frozen-lockfile"], ["run", "build"]]) {
  const run = Bun.spawnSync(["bun", ...args], { cwd: web, stdout: "inherit", stderr: "inherit" });
  if (run.exitCode !== 0) throw new Error(`bun ${args.join(" ")} failed in web/`);
}

const dist = join(web, "dist", "client");
const TYPES: Record<string, string> = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".woff2": "font/woff2",
};

const files: Record<string, { type: string; body: string; base64?: true }> = {};
for (const name of readdirSync(dist, { recursive: true, withFileTypes: true })) {
  if (!name.isFile()) continue;
  const path = join(name.parentPath, name.name).slice(dist.length + 1);
  const type = TYPES[extname(path)];
  if (type == null) throw new Error(`no content type for web/dist/client/${path}`);
  const bytes = readFileSync(join(dist, path));
  files[path] = type.startsWith("text/")
    ? { type, body: bytes.toString("utf8") }
    : { type, body: bytes.toString("base64"), base64: true };
}

const html = files["index.html"]?.body;
if (html == null) throw new Error("web/dist/client/index.html is missing");
const inline = [...html.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)].map(
  (match) => `'sha256-${createHash("sha256").update(match[1]!).digest("base64")}'`,
);

const csp = [
  "default-src 'none'",
  `script-src 'self' ${inline.join(" ")}`,
  // Radix adds <style> tags for scroll locking; styles cannot run code.
  "style-src 'self' 'unsafe-inline'",
  "font-src 'self'",
  "connect-src 'self'",
  "img-src 'self' data:",
  "form-action 'none'",
  "base-uri 'none'",
  "frame-ancestors 'none'",
].join("; ");

writeFileSync(
  join(root, "src", "ui", "assets.ts"),
  `// Generated by scripts/build-ui.ts from web/. Do not edit; run \`bun run build:ui\`.\n\n` +
    `export const UI_CSP = ${JSON.stringify(csp)};\n\n` +
    `/** Built files by path under /ui/; \`index.html\` is the page itself. */\n` +
    `export const UI_FILES: Record<string, { type: string; body: string; base64?: true }> = ${JSON.stringify(files, null, 1)};\n`,
);
console.log(`Embedded ${Object.keys(files).length} files in src/ui/assets.ts`);
